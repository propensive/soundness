package enigmatic

import java.io as ji

import scala.unsafeExceptions.canThrowAny

import anticipation.*

// Cryptographically strong random bytes for the pure-Scala provider: the kernel's `/dev/urandom`
// on Scala Native, whose javalib has no `SecureRandom`; `SecureRandom` on the JVM and
// `crypto.getRandomValues` on Scala.js.
private[enigmatic] object Entropy:
  def bytes(size: Int): Data =
    val output = Array.allocate[Byte](size)
    val stream = ji.FileInputStream("/dev/urandom")
    try fill(stream, output, 0, size) finally stream.close()
    Array.freeze(output)

  // The exclusive array is a parameter, not a capture: separation checking forbids a local
  // function closing over a fresh exclusive array.
  private def fill(stream: ji.InputStream, output: Array[Byte]^, offset: Int, size: Int): Unit =
    if offset < size then
      val count = stream.read(output.raw, offset, size - offset)
      if count < 0 then CryptoFailure.ioFailure("/dev/urandom ended")
      fill(stream, output, offset + count, size)
