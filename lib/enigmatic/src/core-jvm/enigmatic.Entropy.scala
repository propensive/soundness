package enigmatic

import java.security as js

import anticipation.*

// Cryptographically strong random bytes for the pure-Scala provider: the JDK's `SecureRandom`
// here; `crypto.getRandomValues` on Scala.js and `/dev/urandom` on Scala Native.
private[enigmatic] object Entropy:
  private val random: js.SecureRandom = js.SecureRandom()

  def bytes(size: Int): Data =
    val output = Array.allocate[Byte](size)
    random.nextBytes(output.raw)
    Array.freeze(output)
