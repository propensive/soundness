package enigmatic

import anticipation.*

// A stream cipher used as a keystream generator: `xor` combines the data with the keystream of
// the key, nonce and block counter, which both encrypts and decrypts. It is the raw primitive a
// protocol builds its own authenticated construction from — OpenSSH's `chacha20-poly1305` uses
// one ChaCha20 keystream for the packet length and another for the payload — and the counter is
// exposed for exactly that reason. As with an AEAD nonce, a nonce must never repeat under a key.
trait Keystream:
  def nonceSize: Int
  def xor(key: Data, nonce: Data, counter: Int, data: Data): Data
