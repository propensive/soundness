package enigmatic

import scala.reflect.Selectable.reflectiveSelectable

import anticipation.*
import vacuous.*

// AES in Galois/Counter Mode (NIST SP 800-38D): authenticated encryption with a 96-bit nonce
// and a 128-bit tag, as SSH's `aes128-gcm@openssh.com` and `aes256-gcm@openssh.com`, TLS's
// `AES_*_GCM` suites and most of the rest of the modern internet use it. It is a different
// primitive from `Aes over Cbc` and the other block-cipher modes — it authenticates, takes
// associated data, and takes a nonce the caller must never repeat — so it is its own cipher
// rather than a `BlockCipherMode`, and needs no `Permit[Concession.Unauthenticated]`.
object AesGcm:
  given value: [bits <: 128 | 256: ValueOf]
  =>  ( crypto: Crypto { def aesGcm: Crypto.Aead } )
  =>  AesGcm[bits] =
    AesGcm(crypto.aesGcm)

class AesGcm[bits <: 128 | 256: ValueOf](aead: Crypto.Aead)
extends Cipher, Symmetric, Authenticated:
  type Size = bits

  def keySize: bits = valueOf[bits]
  def genKey(): Data = aead.generateKey(keySize)
  def privateToPublic(key: Data): Data = key
  def nonceSize: Int = 12
  def tagSize: Int = 16

  def seal(key: Data, nonce: Data, associated: Data, plaintext: Data): Data =
    aead.seal(key, nonce, associated, plaintext)

  def unseal(key: Data, nonce: Data, associated: Data, ciphertext: Data): Optional[Data] =
    aead.unseal(key, nonce, associated, ciphertext)
