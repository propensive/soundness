// X25519 (RFC 7748), Diffie–Hellman over Curve25519: the key agreement of SSH's
// `curve25519-sha256`, TLS 1.3's default group and WireGuard's. Keys are the curve's fixed 32
// bytes, so there is no size parameter. Like `Ed25519`, it is reached through a structural
// refinement of the provider.
object X25519:
  given value: (crypto: Crypto { def x25519: Crypto.KeyAgreement }) => X25519 =
    X25519(crypto.x25519)

  given keyAlgorithm: X25519 is KeyAlgorithm = new KeyAlgorithm:
    type Self = X25519
    def name: Text = t"X25519"
    def sshName: Optional[Text] = Unset
    def algorithm: Optional[Asn1] = Asn1.Sequence(List(Asn1.ObjectId(KeyAlgorithm.X25519)))

    def conforms(algorithm: Asn1, material: KeyAlgorithm.Material): Boolean =
      KeyAlgorithm.identifier(algorithm).lay(false): (arcs, parameters) =>
        arcs == KeyAlgorithm.X25519 && parameters.absent

class X25519(scheme: Crypto.KeyAgreement) extends Cipher, Agreeing:
  type Size = 256

  def keySize: 256 = 256
  def genKey(): Data = scheme.generateKeyPair(keySize)
  def privateToPublic(keyData: Data): Data = scheme.privateToPublic(keyData)
  def agree(privateKey: Data, publicKey: Data): Data = scheme.agree(privateKey, publicKey)
