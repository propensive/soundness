import vacuous.*

// Authenticated encryption with associated data (AEAD): `seal` encrypts the plaintext and
// authenticates both it and the associated data under a nonce, appending the tag to the
// ciphertext; `unseal` reverses it, and is `Unset` when the tag does not verify — a forgery,
// a wrong key, or a nonce or associated data that differ from the sealing ones. The nonce must
// never repeat under one key; a protocol derives it from a counter, which is why it is supplied
// explicitly rather than drawn at random as a block-cipher IV is.
trait Authenticated:
  def nonceSize: Int
  def tagSize: Int
  def seal(key: Data, nonce: Data, associated: Data, plaintext: Data): Data
  def unseal(key: Data, nonce: Data, associated: Data, ciphertext: Data): Optional[Data]
