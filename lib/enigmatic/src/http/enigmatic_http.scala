package enigmatic

import gesticulate.*
import prepositional.*

// A DER body construes to a `Der` document, whatever it encodes — a certificate, a PKCS#8 key —
// and is decoded from there: `call[Certificate]()` on an `application/pkix-cert` response uses
// `Certificate is Decodable in Der`. A PEM body is one armored block, or a chain of them for
// `application/pem-certificate-chain` (RFC 8555).
package construables:
  given pkixCertConstruable: ("application/pkix-cert" is Construable to Der) = Construable()
  given x509CaCertConstruable: ("application/x-x509-ca-cert" is Construable to Der) = Construable()
  given pkcs8Construable: ("application/pkcs8" is Construable to Der) = Construable()
  given pemConstruable: ("application/x-pem-file" is Construable to Pem) = Construable()

  given pemChainConstruable: ("application/pem-certificate-chain" is Construable to Chain[Pem]) =
    Construable()
