package rudiments

import java.util.concurrent.locks as juclo

import vacuous.*

class Mutex():
  private val lock: juclo.ReentrantLock = juclo.ReentrantLock()

  inline def apply[result](inline block: => result): result =
    lock.lock()
    try block finally lock.unlock()

// A value bound to the current thread for the extent of a block. The store is a `ThreadLocal`
// over `value | Null`, so the unbound state is `null` and reads back as `Unset`; when a block
// unwinds to that state, the entry is removed rather than reset to `null`, so a pooled thread
// does not retain a stale map entry after its last binding ends.
//
// This lives beside `Mutex` rather than in `rudiments.Scoped.scala` because the compiler
// (3.9.0-p16) fails a clean build of this module as soon as package `rudiments` has a
// thirteenth compilation unit — even an empty one: the package object's `export
// rudiments.internal.{Bytes, Digit}` is elaborated before `internal` is entered, and the
// import-suggestion fallback then reports cyclic references in `Atomic`. Move it out once
// that is fixed.
object Scoped:
  def apply[value](): Scoped[value] = new Scoped[value]()

class Scoped[value]():
  private val local: ThreadLocal[value | Null] = ThreadLocal()

  def apply(): Optional[value] = Optional(local.get())

  inline def apply[result](value: value)(inline block: => result): result =
    val previous: value | Null = local.get()
    local.set(value)

    try block finally if previous == null then local.remove() else local.set(previous)
