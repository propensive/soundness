package zeppelin

import gesticulate.*
import prepositional.*
import zephyrine.*

package detectables:
  // A ZIP archive is identified by the index at its end, which a stream cannot reach. Most
  // archives begin with the header of their first entry, but one need not — a self-extracting
  // archive begins with a program — so a stream is only plausibly a ZIP archive.
  given zipDetectable: ("application/zip" is Detectable under Plausible over Probe to Zipfile) =
    Detectable.signature(0x50, 0x4b, 0x03, 0x04)

  // With random access, the end-of-central-directory record is found where the format puts it.
  given zipIndexDetectable
  :   ("application/zip" is Detectable under Likely over Expanse to Zipfile) =

    Detectable.positional(Zipfile.indexed(_))
