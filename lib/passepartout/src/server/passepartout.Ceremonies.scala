package passepartout

import java.util.concurrent as juc

import beneficence.*
import enigmatic.*
import prepositional.*
import telekinesis.*
import vacuous.*

// A web application's store of the ceremonies in progress: the challenge each session was
// sent, kept between making a ceremony's options and checking its answer. A challenge is
// handed back once and then forgotten, so that an answer cannot be offered twice.
class Ceremonies() extends Findable:
  private val pending: juc.ConcurrentHashMap[Session, WebAuthn.Challenge] =
    juc.ConcurrentHashMap()

  // Begins a ceremony for the session: a fresh challenge, which replaces any the session
  // had not answered.
  def begin(session: Session)(using Crypto): WebAuthn.Challenge =
    val challenge = WebAuthn.Challenge()
    pending.put(session, challenge)
    challenge

  // Ends the session's ceremony, giving the challenge its answer must echo — or `Unset` if
  // the session has none pending, which is the case for an answer offered a second time.
  def conclude(session: Session): Optional[WebAuthn.Challenge] = Optional(pending.remove(session))
