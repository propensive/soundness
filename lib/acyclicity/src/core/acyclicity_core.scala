package acyclicity

// Deliberate stdlib opt-out, as in `Dag`.
import scala.collection.immutable.{Map, Set}

import anticipation.*
import denominative.*
import rudiments.*

// The membership test for the `Dot.Identifier` rule: a DOT identifier is any
// non-empty text containing neither a double-quote nor a newline.
private[acyclicity] def dotIdentifierValid(name: Text): Boolean =
  val text = name.s

  text.length > 0 && (0 until text.length).forall: index =>
    val char = text.charAt(index)
    char != '"' && char != '\n'

extension [node](start: node)
  def explore(dependencies: node => Iterable[node]): Dag[node] =
    @tailrec
    def recur(map: Map[node, Set[node]], todo: Set[node], done: Set[node]): Dag[node] =

      if todo.isEmpty then new Dag(map) else
        val key = todo.head

        dependencies(key).pipe: children =>
          recur
            ( map.updated(key, children.to(Set)),
              (todo ++ children.filter(!done(_))) - key,
              done + key )

    recur(Map(), Set(start), Set())
