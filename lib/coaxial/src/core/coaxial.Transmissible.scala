package coaxial

import anticipation.*
import gossamer.*
import hieroglyph.*
import prepositional.*
import zephyrine.*

object Transmissible:
  // Bound directly at `Data`: a subtype parameter instantiates the frozen array at a
  // wildcard capture that cannot flow back into `^{}`.
  given bytes: Data is Transmissible = _.stream

  given stream: [stream <: Chain[Data]] => stream is Transmissible = value =>
    value.stdlib.iterator.stream

  given text: [text <: Text] => CharEncoder => text is Transmissible =
    text => summon[CharEncoder].encoded(text).stream

  given encoder: [message: Encodable in Text] => CharEncoder => message is Transmissible =
    value => value.encode.in[Data].stream

// One call to `serialize` yields the wire form of one message, as a fresh pull
// endpoint. Transports with message framing (a UDP datagram, a WebSocket frame)
// may therefore `memoize` the stream into a single framed unit; byte-stream
// transports write it through the window, zero-copy.
trait Transmissible extends Typeclass.Pure:
  def serialize(message: Self): (Stream[Data] over Credit)^

  def contramap[self2](lambda: self2 -> Self): self2 is Transmissible =
    message => serialize(lambda(message))
