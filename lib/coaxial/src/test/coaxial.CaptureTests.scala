package coaxial

// The module's other suites are not compiled with capture checking; this file opts in, and the
// import is part of the source text, so larceny's compilation of a `demilitarize` block sees it.
import scala.language.experimental.captureChecking

import soundness.*

import socketBackends.javaBaseSockets, strategies.throwUnsafely
import codepages.utf8Codepage, internetAccess.online

// A session lends its connection to a block, and capture checking confines the connection, and
// any stream which reads from it, to that block.
object CaptureTests extends Suite("sockets-capture", m"Socket session confinement tests"):
  def run(): Unit =
    // The `Connectable` for a TCP endpoint captures the `Online` permission, which a context
    // bound on the session instance did not admit (#2565).
    test(m"a TCP session compiles under capture checking"):
      demilitarize:
        def reply(): Data =
          (ip"127.0.0.1" on Port[Tcp](8080)).session: connection ?=>
            connection.send(Stream(t"Who's there?".in[Data]))
            connection.source.memoize
    . assert(_ == Nil)

    test(m"a Unix domain socket session compiles under capture checking"):
      demilitarize:
        def reply(): Data =
          Uds(t"/run/elsinore.sock").session: connection ?=>
            connection.send(Stream(t"Who's there?".in[Data]))
            connection.source.memoize
    . assert(_ == Nil)

    test(m"a connection's stream cannot leave its session"):
      demilitarize:
        def reply() =
          (ip"127.0.0.1" on Port[Tcp](8080)).session: connection ?=>
            connection.source
      . map(_.message)
    . assert(_.exists(_.contains("outlives its scope")))
