package abscission

import anticipation.*
import gossamer.*
import anthology.Artifact

// A closed world of classfiles: the classes a set of entry points reach, and no others, in a
// directory which is a classpath of its own. It is the intermediate-representation node reached
// from `Classfile` through `shrinkEdges`.
object Shrunk extends Artifact.Ir:
  def id: Text = t"shrunk"

  // An executable JAR of a closed world: the application node reached from `Shrunk`. It is a
  // node of its own, and not `Artifact.Jar`, so that a toolchain which has both `jarEdges` and
  // `shrinkEdges` has one path to each.
  object Jar extends Artifact.Application:
    def id: Text = t"shrunk-jar"
