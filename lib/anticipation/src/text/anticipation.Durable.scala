package anticipation

// A shared capability that may be retained across a thread boundary: a monitor, a running
// process, a connection, a channel, a logger, a log sink. A task's body is retained by the worker
// running it, on another thread, and the worker is itself a shared capability classified
// `Durable`, so what it retains must be classified `Durable` too: a body is typed
// `->{caps.any.only[Durable]}`. A `Tactic` is a `caps.Control` capability — it captures a return
// point on the stack of the code that installed it — and so is not `Durable`: a task raises only
// through its own tactic. (Exclusion, `->{caps.any.except[caps.Control]}`, says what a body that
// is merely *run* on another thread may capture, but it is not a classification, so a body a
// shared object *retains* cannot be typed by it.)
trait Durable extends scala.caps.SharedCapability, scala.caps.Classifier
