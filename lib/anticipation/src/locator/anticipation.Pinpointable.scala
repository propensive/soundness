package anticipation

import prepositional.*

// A way of locating an element within a document, as a browser driver understands one: `strategy`
// names the locating scheme in WebDriver's vocabulary (`css selector`, `xpath`, `link text`, `tag
// name`) and `pinpoint` renders a value in that scheme. Selector and path types provide instances
// in their own companions, so a driver can accept them without depending on the libraries which
// define them.
trait Pinpointable extends Typeclass.Pure:
  def strategy: Text
  def pinpoint(value: Self): Text
