package anticipation

import prepositional.*

object Encodable:
  given bytes: Data is Encodable in Data = identity(_)

  // A `Long` encodes to its eight bytes in big-endian order.
  given longData: Long is Encodable in Data =
    long => Array((56 to 0 by -8).map(long >> _).map(_.toByte)*)

  given int: Int is Encodable in Text = _.toString.tt
  given double: Double is Encodable in Text = _.toString.tt
  given byte: Byte is Encodable in Text = _.toString.tt
  given short: Short is Encodable in Text = _.toString.tt
  given long: Long is Encodable in Text = _.toString.tt
  given float: Float is Encodable in Text = _.toString.tt
  given text: Text is Encodable in Text = identity(_)
  given char: Char is Encodable in Text = _.toString.tt
  given string: String is Encodable in Text = _.tt

// A tracked typeclass, not `Typeclass.Pure`: an `Encodable` built from a `Tactic`
// (field codecs summoned during derivation, tactic-raising encoders) retains it,
// and a given that includes a tactic is honestly a capability (Jon, 2026-07-13).
trait Encodable extends Typeclass, Formal:
  private inline def encodable: this.type = this
  def encoded(value: Self): Form

  extension (value: Self) def encode: Form = encoded(value)

  def contramap[self2](lambda: self2 => Self): (self2 is Encodable in Form)^{this, lambda} =
    new Encodable:
      type Self = self2
      type Form = encodable.Form

      def encoded(value: Self): Form = encodable.encoded(lambda(value))
