package camouflage

import java.lang as jl

import anticipation.*
import parasite.*
import prepositional.*
import rudiments.*
import vacuous.*

object Cache:
  def apply[generic: Abstractable across Durations to Long, value](duration: generic)
  :   Cache[value] =

    new Cache[value](duration.generic/1_000_000L)


  def apply[value](): Cache[value] = new Cache(Unset)

class Cache[value](lifetime: Optional[Long]):
  private val mutex: Mutex = Mutex()
  @scala.caps.unsafe.untrackedCaptures
  private var expiry: Long = Long.MaxValue

  @scala.caps.unsafe.untrackedCaptures
  private var value: Promise[value] = Promise()

  def establish(block: => value): value = mutex:
    if expiry < jl.System.currentTimeMillis then value = Promise()

    // A present result is a completed promise; otherwise compute, offer and return it.
    value().or:
      block.tap: result =>
        value.offer(result)
        expiry = lifetime.lay(Long.MaxValue)(_ + jl.System.currentTimeMillis)
