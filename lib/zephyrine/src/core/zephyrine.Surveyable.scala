package zephyrine

import prepositional.*

// A form which is read in place, from a view of the bytes which hold it: an image laid out so
// that what is asked of it is found without the rest being read. An instance is written
// `Form is Surveyable by Flag to Handle`: the handle is provided contextually for the length
// of the block, as a capability which cannot outlive the view it reads from.
//
// It is what lets whatever lends a view -- a mapped file, an image on the heap, one version of
// a name which is published again and again -- offer to open it as a form, when the lender is
// itself a capability, and so cannot be what a typeclass is an instance for. The form is.
trait Surveyable extends Typeclass, Operable, Resultant:
  def survey[result](view: Terrain^, flags: List[Operand])(block: (Result^) ?=> result): result
