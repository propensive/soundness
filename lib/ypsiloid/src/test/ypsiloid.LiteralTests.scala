package ypsiloid

import soundness.*

// A unit of its own, as the other suites which use `demilitarize` are: the block's file is
// compiled again on its own, and an error elsewhere in it would hide the one which is wanted.
object LiteralTests extends Suite("yaml-literals", m"Ypsiloid literal error tests"):
  def run(): Unit =
    test(m"a mapping which is never closed is marked at the end of the literal"):
      demilitarize:
        y"{name: Hamlet, age: 30"
      . map(_.focus)
    . assert(_ == List("0"))

    test(m"a fault within a literal is marked where it is"):
      demilitarize:
        y"[1, 2, : }"
      . map(_.focus)
    . assert(_ == List("}"))

    test(m"a literal's error gives the reason, and no line or column"):
      demilitarize:
        y"{name: Hamlet, age: 30"
      . map(_.message.trim)
    . assert(_ == List("[↯/s.60.2] the YAML is not valid because the flow mapping was not terminated"))
