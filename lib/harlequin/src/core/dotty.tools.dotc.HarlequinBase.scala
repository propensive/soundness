package dotty.tools.dotc

import core.*, Contexts.*

// `ContextBase.initialize` sizes the recursion breadcrumbs from `-Xmax-fuel`, but it also
// initialises `definitions`, which needs the standard library on the compiler classpath. A
// parse-only base never calls it, so it keeps the field's ten slots and `foldOver` overflows on
// the eleventh nested tree (soundness#2284, proscala#19). The field is `private[dotc]`, hence
// this package.
object HarlequinBase:
  def prime(using context: Context): Unit =
    // `handleRecursive` only reads the slots, writing into the operations they hold, so the
    // frozen array is never written through the JVM view; the cast forgets its read
    // capability, which the field, not being capture-checked, cannot carry.
    val operations = Array.fill(context.settings.XmaxFuel.value)(RecursiveOperation.blank())
    context.base.recursiveOperations =
      Array.unsafeJvm(operations).asInstanceOf[scala.Array[RecursiveOperation]]
