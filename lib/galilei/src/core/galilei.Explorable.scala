package galilei

import contingency.*
import prepositional.*
import rudiments.*
import serpentine.*
import vacuous.*

object Explorable:
  // All planes explore identically: the backend lists child names, appended to the parent path
  // (which is well-formed by construction, since each name came from a real directory entry).
  given explorable: [plane: Filesystem]
  =>  ( backend: FilesystemBackend on plane )
  =>  plane is Explorable =

    new Explorable:
      type Self = plane

      def children(path: Path on plane)(using Tactic[Io.Error]): Chain[Path on plane] =
        backend.children(path).map: name => path.unsafeChild(name)(using Unsafe)

trait Explorable extends Typeclass:
  // A listing is strict, so a backend failure is reported here, through the caller's tactic.
  def children(path: Path on Self)(using Tactic[Io.Error]): Chain[Path on Self]
