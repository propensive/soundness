package praxinoscope

import scala.collection.concurrent.TrieMap

import anticipation.*

object Fsa:
  private val cache: TrieMap[String, Fsa] = TrieMap()

  // Builds the matcher for `key` at most once: extractor construction happens per match call,
  // so the generated tables must not be rebuilt each time. `key` is the pattern's string
  // literal, so lookups compare by identity in the common case.
  def of(key: String)(fsa: => Fsa): Fsa = cache.getOrElseUpdate(key, fsa)

// A compile-time-generated finite-state matcher: a whole-input boolean test compiled from a
// specific pattern. A named holder rather than a bare function type so that capture-checked
// consumers can carry one through quoted code without materializing a function type there.
case class Fsa(test: Text => Boolean):
  def matches(text: Text): Boolean = test(text)
