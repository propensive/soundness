// What a successful `Media["…"](detection)` pattern binds: evidence of what was established about
// the content that was matched. A `Detection of "image/gif" under Likely to (Raster in Gif)` says
// that the content was detected as `image/gif`, with a certainty of `Likely`, and that it is read
// as a `Raster in Gif`. A method may demand a certainty of its parameter:
// `Detection of "application/json" under (? <: Likely)`.
//
// The content itself stays with the code that matched it, at the position where it was found: a
// cursor is exclusive, so a detection cannot hold a second way to read it. `read` decodes the
// cursor as the type the detection names.
object Detection:
  final class Bound[media <: Label, limit <: Plausible, result](name: Text) extends Detection:
    type Topic = media
    type Limit = limit
    type Result = result

    def mediaType: MediaType = Media.unsafeParse(name)(using Unsafe)

trait Detection extends Topical, Limited, Resultant:
  type Topic <: Label
  type Limit <: Plausible

  def mediaType: MediaType

  // Reads the whole of `cursor`, from where it stands, as the type this detection names.
  def read(cursor: Cursor[Data, {}]^)(using aggregable: (Result is Aggregable by Data)^): Result =
    aggregable.accept(streamOf(cursor))
