package gesticulate

// How much a detection has established, as a lattice in which a stronger claim is a subtype of a
// weaker one, so "at least `Likely`" is written `under (? <: Likely)`.
//
// The level is fixed by what was examined:
//
// - `Plausible`: what was examined is merely consistent with the format — either because the
//   format designates no identifying structure (a leading `{` opens JSON, but other formats
//   legitimately begin the same way), or because it does but the access at hand cannot reach it
//   (a ZIP file's index is at its end, out of a forward stream's reach).
// - `Likely`: the structure which the format's specification designates as identifying was
//   examined, where the specification locates it, and found — a reserved signature at a fixed
//   offset, or a ZIP file's end-of-central-directory record. A false positive needs coincidence
//   or forgery. Nothing is claimed about the rest of the content being well-formed.
// - `Certain`: the whole content was validated.
sealed trait Plausible
sealed trait Likely extends Plausible
sealed trait Certain extends Likely
