package contingency

import anticipation.*
import fulminate.*

// What `pacify` raises in place of a `Throwable` thrown by foreign code — code written without
// Soundness, such as a compiler, whose failures are not all `Exception`s. The throwable is kept
// as the error's cause, for a diagnostic to show.
object Disturbance:
  private def describe(throwable: Throwable): Message =
    val name: Text = throwable.getClass.nn.getName.nn.tt

    throwable.getMessage match
      case null    => m"foreign code threw $name"
      case message => m"foreign code threw $name with the message, ${message.tt}"

case class Disturbance(throwable: Throwable)(using Diagnostics)
extends fulminate.Error(24, 17, 0)(Disturbance.describe(throwable), throwable)
