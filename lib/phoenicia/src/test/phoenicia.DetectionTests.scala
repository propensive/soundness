package phoenicia

import soundness.*

import detectables.{opentypeDetectable, truetypeDetectable}

object DetectionTests extends Suite("font-detection", m"Phoenicia detection tests"):
  def run(): Unit =
    test(m"a stream with the TrueType version is likely TrueType"):
      Cursor(hex"0001000000120100") match
        case Media["font/ttf", Likely](detection) => true
        case _                                   => false

    . assert(_ == true)

    test(m"a stream which opens with OTTO is likely OpenType"):
      Cursor(hex"4f54544f00090080") match
        case Media["font/otf", Likely](detection) => true
        case _                                   => false

    . assert(_ == true)

    test(m"an OpenType stream is not TrueType"):
      Cursor(hex"4f54544f00090080") match
        case Media["font/ttf", Likely](detection) => true
        case _                                   => false

    . assert(_ == false)
