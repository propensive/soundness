package phoenicia

import anticipation.*
import gossamer.*
import spectacular.*

object Variation:
  object Axis:
    // An OpenType variation axis is a four-character tag. The five registered axes have names;
    // a font's own axes are made from their tags.
    def apply(tag: Text): Axis = tag

    val Weight: Axis = t"wght"
    val Width: Axis = t"wdth"
    val Italic: Axis = t"ital"
    val Slant: Axis = t"slnt"
    val OpticalSize: Axis = t"opsz"

    extension (axis: Axis) def tag: Text = axis

    given showable: Axis is Showable = _.tag
    given inspectable: Axis is Inspectable = axis => t"Variation.Axis(${axis.tag.inspect})"

  opaque type Axis = Text

  // The values a font admits on one of its axes.
  case class Range(axis: Axis, lower: Double, upper: Double):
    def contains(value: Double): Boolean = value >= lower && value <= upper

// A position on one axis of a variable font. The registered weight, width, italic and slant
// axes are set through a face's `Weight`, `Stretch` and `Slant`; a `Variation` is for optical
// size and a font's own axes.
case class Variation(axis: Variation.Axis, value: Double)
