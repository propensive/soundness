package savagery

import soundness.*

import codepages.utf8Codepage
import detectables.svgDetectable

object DetectionTests extends Suite("svg-detection", m"Savagery detection tests"):
  def detect(text: Text): Boolean = detect(text.in[Data])

  def detect(data: Data): Boolean = Cursor(data) match
    case Media["image/svg+xml", Plausible](detection) => true
    case _                                            => false

  def run(): Unit =
    test(m"an svg element is plausibly SVG"):
      detect(t"<svg xmlns=\"http://www.w3.org/2000/svg\"/>")
    . assert(_ == true)

    test(m"an XML declaration is plausibly SVG"):
      detect(t"<?xml version=\"1.0\"?><svg/>")
    . assert(_ == true)

    test(m"an HTML document is not plausibly SVG"):
      detect(t"<!DOCTYPE html>")
    . assert(_ == false)
