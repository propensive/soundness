package scintillate

import scala.beans.BeanProperty

// The JSON side of the Java servers (Netty, Undertow, Jetty, Helidon, the JDK's
// `HttpServer`): Jackson databind serializing a bean per request, as TechEmpower's Java
// entries do.
object RivalJackson:
  class Greeting(@BeanProperty val message: String)

  private val mapper = com.fasterxml.jackson.databind.ObjectMapper()

  def greeting(): Array[Byte] = mapper.writeValueAsBytes(Greeting(HttpWorkload.hello)).nn

  val hello: Array[Byte] = HttpWorkload.hello.getBytes("US-ASCII").nn
  val userPrefix: String = "/user/"
