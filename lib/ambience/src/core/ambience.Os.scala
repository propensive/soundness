package ambience

import anticipation.*
import distillate.*
import gossamer.*
import prepositional.*

object Os:
  // Decoded from the JVM's `os.name`, whose spellings vary by platform and version (`Mac OS X`,
  // `Windows Server 2022`, `SunOS`, …), so the match is on the lowercased prefix.
  given decodable: Os is Decodable in Text = name =>
    val lower = name.lower

    if lower.starts(t"linux") then Linux
    else if lower.starts(t"mac") || lower.starts(t"darwin") then MacOs
    else if lower.starts(t"windows") then Windows
    else if lower.starts(t"freebsd") then FreeBsd
    else if lower.starts(t"openbsd") then OpenBsd
    else if lower.starts(t"netbsd") then NetBsd
    else if lower.starts(t"sunos") || lower.starts(t"solaris") then Solaris
    else if lower.starts(t"aix") then Aix
    else Other(name)

enum Os:
  case Linux, MacOs, Windows, FreeBsd, OpenBsd, NetBsd, Solaris, Aix
  case Other(name: Text)
