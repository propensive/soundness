package decorum

// A single tokenized source line, carrying the derived values that several
// per-line checks previously each rebuilt for themselves: the lexeme array,
// a prefix-sum column table, and the leading-whitespace measurements.
final class Line(val lexemes: IndexedSeq[Lexeme]):
  val arr: Array[Lexeme] = lexemes.toArray

  val cols: Array[Int] =
    val array = new Array[Int](arr.length + 1)
    array(0) = 1
    var i = 0

    while i < arr.length do
      array(i + 1) = array(i) + arr(i).text.length
      i += 1

    array

  val leadingWs: IndexedSeq[Lexeme] = lexemes.takeWhile(_.kind == Sort.Space)
  val rest: IndexedSeq[Lexeme] = lexemes.drop(leadingWs.length)
  val leadingCols: Int = leadingWs.iterator.map(_.text.length).sum
  val visibleLen: Int = cols(arr.length) - 1
  val firstReal: Option[Lexeme] = rest.headOption
  val isBlank: Boolean = firstReal.isEmpty
