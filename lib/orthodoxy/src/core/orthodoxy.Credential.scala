package orthodoxy

import prepositional.*

// A credential for a named security scheme, as an API's specification names it: `("api_key" is
// Credential to Text)` for an API key, `("basicAuth" is Credential to Auth)` for HTTP
// authentication, `("oauth" is Credential to Authorization)` for an OAuth 2 token. A client which
// reads the specification (apoplexy's `Api`) finds the credential for each scheme an operation
// requires by name, checks that its `Result` fits the scheme's kind, and presents it as the
// scheme dictates: as a header, a query parameter or a cookie.
object Credential:
  class Bound[name <: Label, result](val value: result) extends Credential:
    type Self = name
    type Result = result

  def apply[name <: Label, result](value: result): Bound[name, result] = Bound[name, result](value)

trait Credential extends Typeclass, Resultant:
  type Self <: Label
  def value: Result
