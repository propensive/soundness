package degustation

import anticipation.*

// A symbolic reference from an inline body: `Own` names an atom of the same module by key;
// `Foreign` names one in a dependency. Value hashes are resolved at assembly time.
enum ScalaReference:
  case Own(key: Text)
  case Foreign(key: Text)

// One atom of the `tasty/1` discipline, before hashing: the stable key, whether the atom
// is replaceable (an inline or macro body) rather than rigid, the canonical encoding whose hash
// is the atom's value, and the references collected from a replaceable body.
case class ScalaAtom
  ( key:         Text,
    replaceable: Boolean,
    encoding:    Data,
    references:  List[ScalaReference] = List() )
