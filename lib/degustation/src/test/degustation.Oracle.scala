package degustation

import scala.quoted.Quotes
import scala.tasty.inspector as sti

import anticipation.*
import gossamer.*
import murmuration.*
import vacuous.*


// The `tasty/1` reference implementation, kept as the test suite's oracle: drives the compiler's
// own TASTy unpickler — via the tasty-inspector wrapper — over a set of `.tasty` files against a
// dependency classpath, and atomizes the compiler's reflection of what it finds (`Atomizer`).
// `Inspection` in `degustation.core` produces the same atoms without the compiler; the suite
// checks that it does.
object Oracle:

  def atomize(tastyFiles: List[Text], classpath: List[Text]): List[ScalaAtom] =

    var result: scala.List[ScalaAtom] = scala.Nil
    var failure: Optional[Text] = Unset

    object inspector extends sti.Inspector:
      def inspect(using quotes: Quotes)(tastys: scala.List[sti.Tasty[quotes.type]]): Unit =
        try result = Atomizer.atomize(tastys.map(_.ast))
        catch case error: Exception =>
          failure = error.getMessage.nn.tt

    val ok =
      try
        sti.TastyInspector.inspectAllTastyFiles
          (tastyFiles.map(_.s).stdlib, scala.Nil, classpath.map(_.s).stdlib)(inspector)

      catch case error: Exception =>
        throw Oracle.Error(error.getMessage.nn.tt)

    failure.let: detail => throw Oracle.Error(detail)
    if !ok then throw Oracle.Error(t"the compiler reported errors")

    List.from(result)

  class Error(val detail: Text) extends RuntimeException(detail.s)
