package syndesis

import anticipation.*
import contingency.*
import prepositional.*

// A `Discovery.Backend` is a capability (it retains a `Monitor` and its socket), so it is an
// explicit capturing using-parameter rather than a context bound, which would demand a pure
// instance. The tactic is likewise an explicit parameter rather than `raises`: a context-function
// result type would hide the capability parameters from the separation checker.
extension (service: Discovery.Service)
  def advertise[result](description: Discovery.Description)
    ( block: Discovery.Advertisement ?=> result )
    ( using backend: Discovery.Backend^, tactic: Tactic[Discovery.Error] )
  :   result =

    backend.advertise(service, description)(block)

  def browse[result](block: Discovery.Browser ?=> result)
    ( using backend: Discovery.Backend^, tactic: Tactic[Discovery.Error] )
  :   result =

    backend.browse(service)(block)

extension (instance: Discovery.Instance)
  def resolve[duration: Abstractable across Durations to Long](timeout: duration)
    ( using backend: Discovery.Backend^, tactic: Tactic[Discovery.Error] )
  :   Discovery.Resolution =

    backend.resolve(instance, timeout)
