// The framing shared by both roles. A Language Server exchange is `Content-Length`-framed JSON-RPC
// over a byte channel, and the framing is symmetrical: a server reads what a client writes, and a
// client reads what a server writes. Only the endpoints differ — standard input and output for a
// server, a subprocess's pipes or a stream pair for a client — so the framing lives here and each
// role supplies its own channel.
private[exegesis] object LspTransport:
  // A message with its header. The body is encoded twice — once to measure it, once to write it —
  // because `Content-Length` counts bytes, not characters, and a message may not be ASCII.
  def frame(body: Text): Data =
    import charEncoders.utf8Encoder
    val payload: Data = body.in[Data]

    t"Content-Length: ${payload.length}\r\n\r\n$body".in[Data]

  // Reads framed messages from a channel until it is exhausted, handing each to `receive`. The
  // observer sees the message as it arrived — before parsing, so a malformed message is observed
  // too, and without the framing, so both directions read alike in a log.
  def pump(consume source: (Stream[Data] over Credit)^, observer: Lsp.Observer^)
    ( receive: Text => Unit )
  :   Unit =

    import strategies.throwUnsafely

    source.chunks.frames[ContentLength].each: frame =>
      val message: Text = frame.utf8
      observer.received(message)
      receive(message)
