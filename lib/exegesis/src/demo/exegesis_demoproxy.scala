// An example proxy: it launches the language server named by its own arguments, forwards
// everything an editor sends it, and amends two of the answers on the way back — every hover is
// prefixed with the proxy's name, and every diagnostic the server publishes is labelled. Anything
// not registered here — every other method, and every capability this library does not model —
// crosses unchanged, under the editor's own request ids.
//
// Point an editor at `demo-proxy rust-analyzer` (or any other server) in place of the server
// itself.
object DemoLspProxy:
  import Lsp.*

  def main(args: Array[Text]): Unit = cli:
    execute:
      supervise:
        Lsp.proxy(Lsp.Server(guillotine.Command(args*))):
          rewrite.capabilities(_.copy(hoverProvider = true))

          rewrite.hover: hover =>
            hover.copy(contents = MarkupContent(value = t"_(proxied)_ ${hover.contents.value}"))

          rewrite.diagnostics(_.map { report => report.copy(message = t"[demo] ${report.message}") })

      Exit.Ok
