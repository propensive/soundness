package susurration

import anticipation.*
import guillotine.*
import prepositional.*

// How a value becomes the command line an SSH server's shell runs (RFC 4254 §6.5 passes the
// `exec` request's command to the user's shell): a `Text` is run as written, and a guillotine
// `Command` — `sh"git log -1 $branch"` — is quoted argument by argument, so a value with a space
// or a shell character in it stays one argument, as it would locally.
@unexported
object Invocable:
  given text: Text is Invocable = identity(_)

  // Bounded, not bare: `sh"…"` yields a `Command` refined by its executable's name.
  given command: [command <: Command] => command is Invocable = _.escape

// Reached from the umbrella as `Ssh.Invocable`.
@unexported
trait Invocable extends Typeclass:
  def line(self: Self): Text
