package parasite

// The module's other suites are not compiled with capture checking; this file opts in, and the
// import is part of the source text, so larceny's compilation of a `demilitarize` block sees it.
import scala.language.experimental.captureChecking

import soundness.*

import threads.virtualThreads, probates.cancelProbate, strategies.throwUnsafely

// `supervise` lends a `Monitor` to its block, and a task captures the monitor it was started
// under, so capture checking keeps every task within its supervisor.
object CaptureTests extends Suite("concurrency-capture", m"Task confinement tests"):
  def run(): Unit =
    test(m"a task cannot outlive its supervisor"):
      demilitarize:
        val task = supervise(async(6*7))
      . map(_.message)
    . assert(_.exists(_.contains("outlives its scope")))

    // The block's parameter is named in `supervise`'s signature, so the message names it and
    // not a synthetic `contextual$1` (#2565).
    test(m"the escape is reported as the monitor's"):
      demilitarize:
        val task = supervise(async(6*7))
      . map(_.message)
    . assert(_.exists(_.contains("Capability `monitor` outlives its scope")))

    test(m"a task awaited under its supervisor compiles"):
      demilitarize:
        val answer: Int = supervise(async(6*7).await())
    . assert(_ == Nil)

    // A collection may hold tasks, which capture their monitor (#2565).
    test(m"tasks in a list can each be awaited"):
      demilitarize:
        val answers: List[Int] = supervise(List(async(6), async(7)).map(_.await()))
    . assert(_ == Nil)
