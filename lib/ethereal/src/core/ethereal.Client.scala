package ethereal

import scala.language.experimental.pureFunctions

import guillotine.*
import parasite.*
import prepositional.*
import rudiments.*
import turbulence.*
import vacuous.*

object Client:
  @targetName("make")
  def apply[bus <: Matchable](pid: Pid): Client of bus =
    new Client(pid):
      type Topic = bus

// What the daemon keeps of an invocation outside its session: its place on the bus, and the
// `Cli` a signal is dispatched to, which the session's reader may need before the invocation
// has made it.
case class Client(pid: Pid) extends Topical:
  type Topic <: Matchable

  // An `AnyRef` rim: the `Cli` capability crosses the promise between the signal-dispatch
  // thread and the invocation, and a capability type argument cannot (the fiber-crossing
  // recipe; cast at both ends).
  val invocation: Promise[AnyRef] = Promise()
  val bus: Relay[Topic] = Relay()

  def receive(message: Topic): Unit = bus.put(message)
