package honeycomb

import soundness.*

import codepages.utf8Codepage
import detectables.htmlDetectable

object DetectionTests extends Suite("html-detection", m"Honeycomb detection tests"):
  def detect(text: Text): Boolean = detect(text.in[Data])

  def detect(data: Data): Boolean = Cursor(data) match
    case Media["text/html", Plausible](detection) => true
    case _                                        => false

  def run(): Unit =
    test(m"a document type declaration is plausibly HTML"):
      detect(t"<!DOCTYPE html><html></html>")
    . assert(_ == true)

    test(m"an html element in any case is plausibly HTML"):
      detect(t"  <HTML lang=\"en\">")
    . assert(_ == true)

    test(m"other markup is not plausibly HTML"):
      detect(t"<root/>")
    . assert(_ == false)
