package guillotine

import java.io as ji

import scala.unsafeExceptions.canThrowAny

import vacuous.*

// The Scala Native twin of the JVM `PtyProcess`, which allocates and drives its pseudo-terminal
// through the foreign function API (`java.lang.foreign`), absent from Scala Native's javalib.
// Until an implementation over posixlib's `posix_openpt` lands, running a command on a terminal
// raises `Exec.Error`, through the `IOException` that `OnTerminal.lend` already turns into one;
// the class is here so `OnTerminal.Job` has the same type on every platform.
object PtyProcess:
  def apply(builder: ProcessBuilder, width: Int, height: Int, termios: Optional[Termios])
  :   PtyProcess =

    throw ji.IOException("a pseudo-terminal cannot be allocated on Scala Native yet")

class PtyProcess private () extends java.lang.Process:
  def close(): Unit = ()
  def resize(width: Int, height: Int): Unit = ()
  def mode: Termios = Termios.cooked
  def mode_=(termios: Termios): Unit = ()
  def getInputStream(): ji.InputStream = ji.InputStream.nullInputStream().nn
  def getOutputStream(): ji.OutputStream = ji.OutputStream.nullOutputStream().nn
  def getErrorStream(): ji.InputStream = ji.InputStream.nullInputStream().nn
  def waitFor(): Int = 0
  def exitValue(): Int = 0
  def destroy(): Unit = ()
