package guillotine

// How a pipeline's processes are started and wired: Scala Native's javalib has no
// `ProcessBuilder.startPipeline`, so each process is started on pipes and a daemon thread copies
// its predecessor's standard output into its standard input, closing it at end of stream. The
// pipeline's input is still written to the head and its output read from the tail, as on the JVM.
private[guillotine] object Pipelines:
  def start(builders: scala.collection.immutable.Seq[ProcessBuilder])
  :   scala.collection.immutable.List[java.lang.Process] =

    val processes = builders.map(_.start().nn).toList

    processes.zip(processes.tail).foreach: (upstream, downstream) =>
      val pump: Runnable = () =>
        val input = upstream.getInputStream.nn
        val output = downstream.getOutputStream.nn
        try input.transferTo(output) finally output.close()

      val thread = Thread(pump)
      thread.setDaemon(true)
      thread.start()

    processes
