package guillotine

import scala.jdk.CollectionConverters.*

// How a pipeline's processes are started and wired: on the JVM, `ProcessBuilder.startPipeline`
// connects each process's standard output to its successor's standard input in the kernel.
private[guillotine] object Pipelines:
  def start(builders: scala.collection.immutable.Seq[ProcessBuilder])
  :   scala.collection.immutable.List[java.lang.Process] =

    ProcessBuilder.startPipeline(builders.asJava).nn.asScala.toList
