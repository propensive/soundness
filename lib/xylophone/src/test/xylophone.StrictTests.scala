package xylophone

import soundness.*

import strategies.throwUnsafely
import errorDiagnostics.stackTracesDiagnostics

// A unit of its own, referring to nothing defined in a sibling: `demilitarize` recompiles the
// whole file on its own against the classpath, and a name it cannot see there is an error
// outside the block, after which the compiler inlines nothing more — so the block's own error
// never fires, and the capture comes back empty.
case class XLoose[value](value: value)

object StrictTests extends Suite("xml-strict", m"Xylophone strict codec tests"):
  def run(): Unit =
    given XmlSchema = XmlSchema.Freeform

    test(m"`codecs.strict` rejects a type with no direct codec"):
      val errors = demilitarize:
        import codecs.strict
        XLoose(7).in[Text over Xml]

      errors.map(_.message.contains("has no direct codec"))
    . assert(_ == List(true))
