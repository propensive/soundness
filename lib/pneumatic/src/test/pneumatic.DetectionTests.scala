package pneumatic

import soundness.*

import detectables.{gzipDetectable, xzDetectable}

object DetectionTests extends Suite("compression-detection", m"Pneumatic detection tests"):
  def run(): Unit =
    test(m"a compressed gzip stream is likely gzip"):
      Cursor(Data(1, 1, 2, 3, 5, 8).compress[Gzip]) match
        case Media["application/gzip", Likely](detection) => true
        case _                                           => false

    . assert(_ == true)

    test(m"a compressed XZ stream is likely XZ"):
      Cursor(Data(1, 1, 2, 3, 5, 8).compress[Xz]) match
        case Media["application/x-xz", Likely](detection) => true
        case _                                           => false

    . assert(_ == true)

    test(m"an XZ stream is not gzip"):
      Cursor(Data(1, 1, 2, 3, 5, 8).compress[Xz]) match
        case Media["application/gzip", Likely](detection) => true
        case _                                           => false

    . assert(_ == false)

    test(m"a gzip stream is not XZ"):
      Cursor(Data(1, 1, 2, 3, 5, 8).compress[Gzip]) match
        case Media["application/x-xz", Likely](detection) => true
        case _                                           => false

    . assert(_ == false)
