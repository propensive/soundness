package hallucination

import anticipation.*
import contingency.*
import gesticulate.*

object Bmp:
  def apply(): Rasterizable = rasterization

  given rasterization: Bmp is Rasterizable:
    def name: Text = "BMP".tt
    def mediaType = media"image/bmp"
    def alpha: Boolean = false

    def decode(data: Data): Raster raises Raster.Error = BmpBackend.decode(this, data)
    def encode(raster: Raster): Data = BmpBackend.encode(this, raster)
    def sniff(data: Data): Boolean = (data.length > 1 && data.readable(0) == 0x42 && data.readable(1) == 0x4d)

sealed trait Bmp
