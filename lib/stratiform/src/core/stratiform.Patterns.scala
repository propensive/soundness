package stratiform

import scala.collection.concurrent.TrieMap

import anticipation.*
import contingency.*
import praxinoscope.*
import vacuous.*

// Compiled RE2 pattern constraints (§21.8), memoised by pattern text.
//
// Patterns live in the schema model as `Text`, because a `Tels` must stay a
// pure, structurally-comparable, BinTEL-round-trippable value; a compiled
// `Motif` belongs to none of that. But compiling one is a full recursive-
// descent parse plus a program compilation, and document validation asks for
// the same handful of patterns once per scalar value, so the outcome is cached
// here instead.
//
// The cache is keyed on the pattern's `String` so interned literals hit on
// identity, and it stores the *outcome*, so an invalid pattern is not
// re-parsed on every attempt either. It is process-global and unbounded, which
// is acceptable because the keys are schema text: few, and long-lived.
object Patterns:
  private val motifs: TrieMap[String, Optional[Motif]] = TrieMap()

  // `Unset` for a pattern that is not valid RE2. The caller decides what that
  // means: E222 at schema-validity time, and fail-closed everywhere else.
  def compile(pattern: Text): Optional[Motif] =
    motifs.getOrElseUpdate(pattern.s, safely[Motif.Error](Motif.parse(pattern)))
