// Names the binary encoding of a case-class field which is a scalar (§21.7 of the TEL
// specification): the derived schema declares the field with that `encoding`, so that BinTEL
// and RaTEL store its values as the bytes of the codec bound to the name -- `u32`, `i64`,
// `uuid` and the other standard codecs, or one the application binds -- instead of as text.
final class encoding(name: Text) extends StaticAnnotation
