package octogenarian

// The wall clock a new commit is stamped with. Scala Native's javalib has no `java.time`, so the
// offset is not known: commits made on Scala Native are stamped in UTC (`+0000`), which git
// records faithfully.
private[octogenarian] object SystemClock:
  def now(): (Long, Int) = (System.currentTimeMillis/1000, 0)
