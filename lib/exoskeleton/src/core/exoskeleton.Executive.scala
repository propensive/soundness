package exoskeleton

import ambience.*
import anticipation.*
import beneficence.*
import rudiments.*
import turbulence.*
import vacuous.*

trait Executive extends Findable:
  type Return
  type Interface <: Cli

  def invocation
    ( fullArguments:    List[Text],
      environment:      Environment,
      workingDirectory: WorkingDirectory,
      stdio:            Stdio,
      entrypoint:       Entrypoint^,
      login:            Login )
    ( using interpreter: Interpreter )
  :   Interface

  // The block sees `Cli` (not `Interface`): every entry point routes a `Cli ?=> Return` block
  // here, and with `Cli` a capability, adapting a `Cli ?=>` context function to an
  // abstract-`Interface ?=>` one trips capture-root unification.
  def process(cli: Interface)(result: Cli ?=> Return): Exit

  // Re-run the application's pure portion in tab-completion mode with synthesized argument
  // prefixes to discover its subcommand/flag structure as a `Help` tree, rooted at `command`.
  // Only the completions executive can do this (its `Interface` is `Cli`, so a `Completion` is
  // a valid interface); every other executive returns `Unset`.
  def help
    ( command:          Text,
      environment:      Environment,
      workingDirectory: WorkingDirectory,
      stdio:            Stdio,
      login:            Login )
    ( block: Interface ?=> Return )
    ( using interpreter: Interpreter )
  :   Optional[Help] = Unset
