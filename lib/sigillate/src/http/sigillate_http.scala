// A key set from the URL its owner publishes it at — an identity provider's `jwks_uri`, or
// the `jku` of a header one has decided to trust. The request goes through whichever
// `Http.Client` is in scope; anything but a `200` carrying a key set is `Unavailable`.
extension (jwks: Jwks.type)
  def retrieve(url: HttpUrl)
    ( using Online, (Http.Event is Loggable)^, Http.Client onto Origin["http" | "https"] )
    ( using Tactic[Jose.Error], Diagnostics )
  :   Jwks =

    def unavailable(detail: Text): Jose.Error = Jose.Error(Jose.Error.Reason.Unavailable(detail))

    val response =
      mitigate:
        case Connect.Error(reason) => unavailable(t"the connection to $url failed")

      . protect(url.fetch())

    response.status match
      case Http.Ok =>
        mitigate:
          case Parse.Error(_, _, _)  => unavailable(t"the response from $url was not JSON")
          case Truncation.Error(_)   => unavailable(t"the response from $url was cut short")
          case Json.Error(_)         => unavailable(t"the response from $url was not a key set")
          case Http.Error(status, _) => unavailable(t"$url answered with the status $status")

        . protect(response.receive[Json].as[Jwks])

      case status =>
        abort(unavailable(t"$url answered with the status $status"))
