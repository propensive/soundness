package proscenium

// How a key is hashed, when it is a key of a `Map`: with `Equatable`, which says when two keys
// are the same, it is the policy a map keeps its keys by. A map is made with the policy in
// scope where it is built (`Map.build`), and the instance found for any type, unless another is
// chosen, is the universal one: `##`, the hash the standard library's maps use. Two keys which
// are the same under the `Equatable` chosen must have the same hash under the `Hashable` chosen
// with it.
object Hashable:
  // One instance for every type: it reads nothing of the type it is asked for.
  object Universal extends Hashable:
    type Self = Any
    def hash(value: Any): Int = value.##

  given universal: [value] => (value is Hashable) = Universal.asInstanceOf[value is Hashable]

  def apply[value](lambda: value -> Int): value is Hashable = new Hashable:
    type Self = value
    def hash(value: value): Int = lambda(value)

trait Hashable extends scala.caps.Pure:
  type Self
  def hash(value: Self): Int
