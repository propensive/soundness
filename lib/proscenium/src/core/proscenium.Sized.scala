package proscenium

// A phantom marker recording a *proof of length* in a value's type, the counterpart of
// `Populated` for fixed-layout data: a tar header is 512 bytes, a compass rose has eight
// points, a COSE envelope starts with its tag byte. The proof is minted three ways: the
// constructors whose length argument is a literal (`Array.fill(512)(…)`, `Data.fill(8)(…)`)
// brand their result by construction; a producer that fixes a layout declares the brand on its
// result; and `sized[n]` checks a value's length once and records it, as `occupied` records
// non-emptiness. A literal ordinal below the length is then *confined by construction*: the
// `apply` taking an `Ordinal { type N0 = i }` on a `Sized[n]` receiver decides `i < n` at
// compile time, so the read is total and an out-of-range literal is a compile error.
//
// A structural refinement, not a trait, for the same reason as `Populated`: it erases to the
// underlying value. The length is a type-level `Int`, so `scala.compiletime.ops.int` can
// combine proofs (`Sized[n + m]` for a concatenation) and compare them.
type Sized[length <: Int] = Any { type Length = length }
