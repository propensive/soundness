package proscenium

// When two keys of a `Map` are the same key: with `Hashable`, the policy a map keeps its keys
// by (see there). The instance found for any type, unless another is chosen, is the universal
// one, `==`.
object Equatable:
  // One instance for every type: it reads nothing of the type it is asked for.
  object Universal extends Equatable:
    type Self = Any
    def equal(left: Any, right: Any): Boolean = left == right

  given universal: [value] => (value is Equatable) = Universal.asInstanceOf[value is Equatable]

  def apply[value](lambda: (value, value) -> Boolean): value is Equatable = new Equatable:
    type Self = value
    def equal(left: value, right: value): Boolean = lambda(left, right)

  // Keys told apart by which object they are, and not by what they contain: two structurally
  // equal values in different places stay distinct, and a large value is never hashed through.
  // It is both halves of the policy at once, so that one import chooses it.
  object Identity extends Hashable, Equatable:
    type Self = AnyRef
    def hash(value: AnyRef): Int = System.identityHashCode(value)
    def equal(left: AnyRef, right: AnyRef): Boolean = left eq right

trait Equatable extends scala.caps.Pure:
  type Self
  def equal(left: Self, right: Self): Boolean

// The policies a map's keys can be kept by, other than the universal `==` and `##`: each is
// imported by name where a map is built.
package equalities:
  // By reference: `eq`, and the identity hash.
  given identityEquality: [key <: AnyRef] => (key is (Hashable & Equatable)) =
    Equatable.Identity.asInstanceOf[key is (Hashable & Equatable)]
