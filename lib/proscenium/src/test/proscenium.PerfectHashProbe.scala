package proscenium

import scala.quoted.*

// A macro for the suite to see a program spliced: the keys are generated from `seed` at
// compile time, searched, and the program for them inlined over `key`.
object PerfectHashProbe:
  def key(seed: Long, index: Int): Long =
    var value = seed + index*0x9E3779B97F4A7C15L
    value = (value ^ (value >>> 30))*0xBF58476D1CE4E5B9L
    value = (value ^ (value >>> 27))*0x94D049BB133111EBL
    value ^ (value >>> 31)

  def keys(seed: Long, count: Int): scala.Array[Long] = scala.Array.tabulate(count)(key(seed, _))

  inline def spliced(inline seed: Long, inline count: Int)(key: Long): Int =
    ${expand('seed, 'count, 'key)}

  def expand(seed: Expr[Long], count: Expr[Int], key: Expr[Long])(using Quotes): Expr[Int] =
    val hash = PerfectHash.search(keys(seed.valueOrAbort, count.valueOrAbort), 1)

    if hash == null then quotes.reflect.report.errorAndAbort("no perfect hash was found") else
      ' {
          val table = ${hash.quotedTable}
          ${hash.quoted(List(key))('table)}
        }
