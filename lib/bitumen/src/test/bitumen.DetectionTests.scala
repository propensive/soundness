package bitumen

import soundness.*

import detectables.tarDetectable

object DetectionTests extends Suite("tar-detection", m"Bitumen detection tests"):
  def run(): Unit =
    test(m"a header block with the ustar magic is likely TAR"):
      Cursor(Data.fill(512) { index => if index >= 257 && index < 262 then t"ustar".s.getBytes.nn(index - 257) else 0.toByte }: Data) match
        case Media["application/x-tar", Likely](detection) => true
        case _                                            => false

    . assert(_ == true)

    test(m"a block of zeros is not TAR"):
      Cursor(Data.fill(512)(_ => 0.toByte): Data) match
        case Media["application/x-tar", Likely](detection) => true
        case _                                            => false

    . assert(_ == false)

    test(m"a stream shorter than a header is not TAR"):
      Cursor(hex"7573746172") match
        case Media["application/x-tar", Likely](detection) => true
        case _                                            => false

    . assert(_ == false)
