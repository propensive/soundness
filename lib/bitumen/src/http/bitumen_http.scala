package bitumen

import gesticulate.*
import prepositional.*

// `application/x-tar` is the media type every TAR archive is served as (none is registered); a
// Debian package is an `ar` archive, so it construes to an `Arfile` as `application/x-archive`
// does. A compressed archive (`application/gzip`) is a content encoding rather than a format,
// and has no carrier of its own.
package construables:
  given tarConstruable: ("application/x-tar" is Construable to Tarfile) = Construable()
  given arConstruable: ("application/x-archive" is Construable to Arfile) = Construable()

  given debConstruable: ("application/vnd.debian.binary-package" is Construable to Arfile) =
    Construable()
