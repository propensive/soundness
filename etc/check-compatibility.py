#!/usr/bin/env python3
"""Regenerate the platform matrix in doc/compatibility.tsv from build.mill and fail if the
committed copy has drifted from it (roadmap item plat-1).

The matrix has one row per library under lib/. Its platform columns are derived, not written:
a component's `scalaJs`/`scalaNative` overrides (defaults: `scalaJs = true`, `scalaNative =
scalaJs`) and its `sources`/`jsSources`/`nativeSources` source sets decide whether the library's
primary component (`core`, or the first declared) cross-compiles, and whether its platform
functionality has a backend there or only on the JVM. The `submodules` column is generated too.
Only `notes` — the reason for every exclusion — is written by hand, and it is carried over from
the committed file by module name; an exclusion with no reason fails the check.

Usage:
    python3 etc/check-compatibility.py            # diff against doc/compatibility.tsv; exit 1 on drift
    python3 etc/check-compatibility.py --update   # rewrite doc/compatibility.tsv, keeping notes
    python3 etc/check-compatibility.py --table    # print the regenerated matrix
Run by `make build`.
"""
import os, re, sys

BUILD = 'build.mill'
TSV = 'doc/compatibility.tsv'
COLUMNS = ['module', 'jvm', 'js', 'native', 'wasm', 'submodules', 'notes']

LIBRARY = re.compile(r'^object (\w+) extends Library', re.M)
COMPONENT = re.compile(
    r'^  object (`?\w+`?)\s*(?:\n\s*)?extends\s+(\w+)(.*?)(?=^  object |\Z)', re.M | re.S)
FLAG = {platform: re.compile(r'override def scala%s\s*=\s*(true|false)' % platform)
        for platform in ('Js', 'Native')}
SOURCES = re.compile(r'override def (sources|jsSources|nativeSources)\s*=\s*Task\.Sources\((.*?)\)', re.S)
SOURCE_DIR = re.compile(r'os\.up / "([\w-]+)"')

HEADER = '''\
# Soundness module compatibility by platform target. One row per library under lib/.
# Generated by `python3 etc/check-compatibility.py --update` from build.mill (per-component
# `scalaJs`/`scalaNative` flags and `sources`/`jsSources`/`nativeSources` source sets); `make build`
# runs the script and fails if this file has drifted. Only the `notes` column is written by hand.
#
# jvm   : yes  = runs on the JVM (every module).
# js    : yes  = the module's primary component (`core`, or the first declared) cross-compiles to
#                Scala.js, and its platform functionality is available there.
#         core = the primary component cross-compiles, but the module's platform functionality
#                has a JVM-only backend (a `jvm` submodule, or a `*-jvm` source set with no
#                replacement for this platform) — e.g. hellenism's classpath.
#         no   = the primary component is JVM-only (`scalaJs = false`); see notes for why.
# native: cross-compilation to Scala Native, read the same way as `js`. `scalaNative` defaults to
#         `scalaJs`, so this differs only where a module overrides it.
# wasm  : wasi = has a WebAssembly/WASI backend submodule (`wasi` or `wasm`).
#         js   = no WASI backend, but compiles to WebAssembly via the Scala.js -> scala-wasm pipeline.
#         core = as `js` = core: the backend is JVM-only.
#         no   = JVM-only.
# submodules : generated: the platform-specific source sets of the primary component (`backends`),
#         and every other component whose platforms differ from the primary's, by its own
#         platforms (`JVM-only`, `JS-only`, `Native-only`, `everywhere`).
# notes : hand-written: the reason for every `no` or `core` cell. Must be non-empty for such rows.
'''


def parse_build():
    text = open(BUILD).read()
    starts = [match.start() for match in LIBRARY.finditer(text)] + [len(text)]
    libraries = {}
    for begin, end in zip(starts, starts[1:]):
        block = text[begin:end]
        name = LIBRARY.match(block).group(1)
        components = {}
        for match in COMPONENT.finditer(block):
            component, kind, body = match.group(1).strip('`'), match.group(2), match.group(3)
            if kind not in ('Component', 'BareComponent'):
                continue
            js = FLAG['Js'].search(body)
            js = js.group(1) == 'true' if js else True
            native = FLAG['Native'].search(body)
            native = native.group(1) == 'true' if native else js
            # `None`: not overridden — the platform compiles the JVM module's `sources` as they are.
            sources = {'sources': [], 'jsSources': None, 'nativeSources': None}
            for sources_match in SOURCES.finditer(body):
                sources[sources_match.group(1)] = SOURCE_DIR.findall(sources_match.group(2))
            components[component] = {'js': js, 'native': native, 'sources': sources}
        libraries[name] = components
    return libraries


def platform_cell(components, primary, platform):
    """`yes`, `core` or `no` for one platform (`js` or `native`)."""
    if not primary[platform]:
        return 'no'
    sources = primary['sources']
    platform_sets = sources['jsSources' if platform == 'js' else 'nativeSources']
    # A platform source set naming a replacement for the JVM backend (`core-native`, `native`,
    # `core-portable`, …) is a backend of its own; one that only drops the `*-jvm` set, or a
    # `jvm` sibling component that this platform excludes, leaves the functionality JVM-only.
    if platform_sets:
        return 'yes'
    if platform_sets == [] and any(name.endswith('-jvm') for name in sources['sources']):
        return 'core'
    jvm = components.get('jvm')
    if jvm is not None and not jvm[platform]:
        return 'core'
    return 'yes'


def submodules(components, primary_name, primary):
    parts = []
    sets = sorted(set(sum((names or [] for names in primary['sources'].values()), [])))
    if sets:
        parts.append('backends: ' + '+'.join(sets))
    # Every other component whose platform pair differs from the primary's, by its own pair.
    LABELS = {(False, False): 'JVM-only', (True, False): 'JS-only', (False, True): 'Native-only',
              (True, True): 'everywhere'}
    groups = {label: [] for label in LABELS.values()}
    for name, component in components.items():
        pair = (component['js'], component['native'])
        if name != primary_name and pair != (primary['js'], primary['native']):
            groups[LABELS[pair]].append(name)
    for label, names in groups.items():
        if names:
            parts.append('%s: %s' % (label, ', '.join(names)))
    return '; '.join(parts)


def generate(notes):
    libraries = parse_build()
    rows = []
    for library in sorted(os.listdir('lib')):
        components = libraries.get(library, {})
        if not components:
            rows.append([library, 'yes', '?', '?', '?', '', notes.get(library, '')])
            continue
        primary_name = 'core' if 'core' in components else next(iter(components))
        primary = components[primary_name]
        js = platform_cell(components, primary, 'js')
        native = platform_cell(components, primary, 'native')
        if any(name in components for name in ('wasi', 'wasm')):
            wasm = 'wasi'
        else:
            wasm = {'yes': 'js', 'core': 'core', 'no': 'no'}[js]
        rows.append([library, 'yes', js, native, wasm, submodules(components, primary_name, primary),
                     notes.get(library, '')])
    return rows


def read_committed():
    """The committed rows, laid out in COLUMNS order whatever columns the file's header names."""
    rows, header = [], COLUMNS
    for line in open(TSV):
        if line.startswith('#') or not line.strip():
            continue
        fields = line.rstrip('\n').split('\t')
        if fields[0] == 'module':
            header = fields
            continue
        by_name = dict(zip(header, fields))
        rows.append([by_name.get(column, '') for column in COLUMNS])
    return rows


def write(rows):
    with open(TSV, 'w') as file:
        file.write(HEADER)
        file.write('\t'.join(COLUMNS) + '\n')
        for row in rows:
            file.write('\t'.join(row) + '\n')


def main():
    committed = read_committed() if os.path.exists(TSV) else []
    notes = {row[0]: row[-1] for row in committed}
    rows = generate(notes)

    if '--table' in sys.argv:
        for row in [COLUMNS] + rows:
            print('\t'.join(row))
        return

    if '--update' in sys.argv:
        write(rows)
        print('wrote %s (%d rows)' % (TSV, len(rows)))

    failed = False
    committed_by_name = {row[0]: row for row in committed}
    for row in rows:
        old = committed_by_name.get(row[0])
        if '--update' not in sys.argv and old != row:
            failed = True
            print('%s: drift' % row[0])
            print('  committed: %s' % ('\t'.join(old) if old else '(no row)'))
            print('  generated: %s' % '\t'.join(row))
        if any(cell in ('no', 'core', '?') for cell in row[2:5]) and not row[-1]:
            failed = True
            print('%s: exclusion without a reason in `notes`' % row[0])
    for name in committed_by_name:
        if not os.path.isdir(os.path.join('lib', name)):
            failed = True
            print('%s: row for a library that no longer exists' % name)
    if failed:
        print('doc/compatibility.tsv is out of date: run `python3 etc/check-compatibility.py --update` '
              'and fill in `notes` for any new exclusion.')
    sys.exit(1 if failed else 0)


if __name__ == '__main__':
    main()
